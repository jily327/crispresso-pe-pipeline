"""Session-scoped export byte identity, separate from scientific verification.

Historical files can have their summary values checked, but no unsigned on-disk
receipt is trusted as proof of original generated bytes. Opening never writes.
"""
from pathlib import Path
import stat
from peanalyzer.workflow_storage import no_symlinks, sha
from peanalyzer.gui.summary_workbook import FILENAME, verify_summary

EXCEL_LOCK = '~$' + FILENAME
PRESENTATION_FILES = frozenset((FILENAME, EXCEL_LOCK))


def workbook_hash(root):
    path = no_symlinks(Path(root) / FILENAME)
    try:
        mode = path.stat().st_mode
    except FileNotFoundError:
        return None
    if not stat.S_ISREG(mode):
        raise ValueError('The export is not a regular file')
    return sha(path)


class ExportTracker:
    def __init__(self):
        self.records = {}
        self.warnings = {}

    def generated(self, root):
        checksum = workbook_hash(root)
        if checksum is None:
            raise ValueError('Generated workbook disappeared')
        self.records[root] = (checksum, 'GENERATED')

    def warn(self, root, exc):
        self.warnings[root] = ('Scientific analysis completed. Optional Excel export could not be generated or verified '
            f'({type(exc).__name__}). Verified results remain available; existing files were preserved.')

    def capture(self, root, view, plan):
        if root in self.records:
            return
        checksum = None
        kind = 'UNVERIFIED'
        try:
            checksum = workbook_hash(root)
            if checksum is not None:
                verify_summary(root, view, plan)
                if workbook_hash(root) != checksum:
                    raise ValueError('Workbook changed during its value check')
                kind = 'CONTENTS_MATCH'
        except Exception:
            # Optional presentation parsing cannot invalidate verified science.
            kind = 'UNVERIFIED'
        self.records[root] = (checksum, kind)

    def status(self, root):
        baseline, kind = self.records.get(root, (None, 'UNVERIFIED'))
        current = None
        try:
            current = workbook_hash(root)
            if current is None:
                state, message = 'MISSING', 'Excel summary is not present. Verified scientific results remain available.'
            elif baseline is None:
                state, message = 'UNVERIFIED', 'Workbook appeared after opening. Its export integrity is not verified.'
            elif current != baseline:
                state, message = 'CHANGED', 'Workbook bytes changed. This file is no longer an unchanged verified export.'
            elif kind == 'GENERATED':
                state, message = 'UNCHANGED', 'Workbook bytes match the export generated by this server session.'
            elif kind == 'CONTENTS_MATCH':
                state, message = 'CONTENTS_MATCH', 'Summary counts match verified science. Original generated bytes are not authenticated.'
            else:
                state, message = 'UNVERIFIED', 'Workbook values could not be verified against the scientific results.'
        except Exception:
            state, message = 'UNREADABLE', 'Workbook integrity could not be checked. Scientific verification is independent.'
        return dict(state=state, message=message, warning=self.warnings.get(root), sha256=current,
            baseline_sha256=baseline, baseline_kind=kind)

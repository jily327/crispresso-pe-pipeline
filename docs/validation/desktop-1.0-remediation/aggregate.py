"""Aggregate terminal focused results; refuse partial or failed qualification."""
import hashlib,json,subprocess,xml.etree.ElementTree as ET
from pathlib import Path
root=Path('/workspace/v1-final-remediation');repo=Path('/workspace/crispresso-pe-pipeline-v1')
results={}
for label in ('source','wheel'):
 for kind in ('focused','integration'):
  s=ET.parse(root/f'{label}-{kind}.xml').getroot().find('testsuite');r=dict(s.attrib)
  assert all(int(r[k])==0 for k in ('errors','failures','skipped')),r
  assert int(r['tests'])==(251 if kind=='focused' else 4),r
  results[f'{label}_{kind}']=r
 browser=json.loads((root/f'{label}-browser-summary.json').read_text())
 assert set(browser)=={'viewer','run','recovery','practical'}
 assert sum(s['expected'] for s in browser.values())==37
 assert all(not s['unexpected'] and not s['flaky'] and not s['skipped'] for s in browser.values())
 results[f'{label}_browser']={'total':37,'suites':browser}
front=json.loads((root/'frontend.json').read_text())
assert front['success'] and front['numFailedTests']==front['numPendingTests']==0
results['frontend']={k:front[k] for k in ('numTotalTests','numPassedTests','numFailedTests','numPendingTests','success')}
pack=json.loads((root/'packaging.json').read_text());assert pack['member_count']==93 and pack['all_package_members_identical']
results['packaging']={k:pack[k] for k in ('candidate','member_count','all_package_members_identical','archives')}
results['wheel_import']=json.loads((root/'wheel-import.json').read_text());assert 'site-packages' in results['wheel_import']['import_path']
assert results['wheel_import']['version']=='1.0.0'
results['science_preservation']=json.loads((root/'science-preservation.json').read_text())
assert results['science_preservation']['frozen_science_count']==70
for name,expected in results['science_preservation']['sha256'].items():assert hashlib.sha256((repo/name).read_bytes()).hexdigest()==expected
results['historical']=json.loads((root/'historical-compatibility.json').read_text())
assert len(results['historical'])==3 and all(x['bytes_unchanged'] and x['mtimes_unchanged'] for x in results['historical'])
alsw=json.loads((root/'alsw-excel-parity.json').read_text());assert sum(len(r['rows']) for r in alsw)==19
results['alsw']={'rows':19,'all_exact_counts_match':all(r['all_rows_match_authoritative_target_counts'] and r['historical_files_unchanged'] for r in alsw),'basis':'Fresh export/value comparison after rehashing prior independently verified stored source files; no raw-data science rerun.'}
parity=[]
for label in ('source','wheel'):
 paths=list((root/f'{label}-integration-tmp').glob('**/outputs/uploaded/metrics/*/*/result.json'))
 assert len(paths)==2,paths
 for p in paths:
  d=json.loads(p.read_text())
  if 'target_metrics' in d:
   row=d['target_metrics']['total_precise_pe'];mode='precise_edit';expected=[2,24]
  else:row=d['metrics']['indel_fraction'];mode='indel_nuclease';expected=[8,20]
  counts=[row['numerator'],row['denominator']];assert counts==expected,(mode,counts)
  parity.append({'installation':label,'mode':mode,'counts':counts,'metric_file':str(p),'sha256':hashlib.sha256(p.read_bytes()).hexdigest()})
results['real_core_counts']=parity
results['initial_nonfinal_run']={'result':'249 passed, 2 SOFTWARE_CHANGED failures','cause':'Qualification overlapped a Git commit and package build in the same source checkout; source identity changed. Replaced by a complete serial run at the fixed implementation commit. No production code changed to silence the guard.'}
results['limitations']=['Native Linux and Chromium tested. Actual Windows/WSL and Microsoft Excel were unavailable; Explorer launch/exit and Excel file lifecycle are automated simulations.','Historical workbooks authenticate matching Summary values, not original generated bytes. Generated-byte identity is session-scoped and labelled explicitly.','No full 1,999-test suite rerun: focused changed-boundary, lifecycle, recovery, real-Core, browser and packaging gates used; protected scientific modules are byte-identical.']
(root/'qualification.json').write_text(json.dumps(results,indent=2)+'\n')
print('All final focused qualification gates passed.')

"""Generate transport types from the Python presentation models, never science."""
import inspect
from pathlib import Path
from peanalyzer.gui import models


def ts(schema):
    if '$ref' in schema:
        return schema['$ref'].split('/')[-1]
    if 'const' in schema:
        import json
        return json.dumps(schema['const'])
    if 'enum' in schema:
        import json
        return ' | '.join(json.dumps(x) for x in schema['enum'])
    if 'anyOf' in schema:
        return ' | '.join(ts(s) for s in schema['anyOf'])
    kind=schema.get('type')
    if kind=='array':return f'Array<{ts(schema["items"])}>'
    if kind=='object':return 'Record<string, unknown>'
    return {'string':'string','integer':'number','number':'number','boolean':'boolean','null':'null'}.get(kind,'unknown')


def generate():
    output=['// Generated by scripts/generate_viewer_types.py. Do not edit by hand.\n']
    for name,cls in inspect.getmembers(models,inspect.isclass):
        if cls.__module__!=models.__name__ or name=='Model':continue
        schema=cls.model_json_schema()
        output.append('export interface '+name+' {')
        for key,value in schema.get('properties',{}).items():
            output.append(f'  {key}: {ts(value)};')
        output.append('}\n')
    return '\n'.join(output)


if __name__=='__main__':
    Path('frontend/src/models/api.ts').write_text(generate())
